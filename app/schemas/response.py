from typing import Optional

from pydantic import BaseModel, ConfigDict, Field


class ClassificationResponse(BaseModel):
    """
    Represent the classification result returned by the API.

    Includes the assigned category, urgency, complexity, confidence score,
    routing target, explanation, and classification performance metadata.
    """

    model_config = ConfigDict(extra="forbid")

    request_id: str = Field(
        ...,
        min_length=1,
        description="Unique identifier for the request.",
    )
    category: str = Field(
        ...,
        description="Determined query category.",
    )
    urgency: str = Field(
        ...,
        description="Determined urgency level.",
    )
    complexity: str = Field(
        ...,
        description="Determined complexity level.",
    )
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Classification confidence score between 0.0 and 1.0.",
    )
    target_agent: str = Field(
        ...,
        min_length=1,
        description="Intended handler or routing target.",
    )
    reason: str = Field(
        ...,
        min_length=1,
        description="Explanation supporting the classification decision.",
    )
    requires_clarification: bool = Field(
        ...,
        description="Whether additional user clarification is required.",
    )
    classification_latency_ms: float = Field(
        ...,
        ge=0.0,
        description="Time spent classifying the query, in milliseconds.",
    )
    status: str = Field(
        default="success",
        description="Classification operation status.",
    )


class ChatResponse(BaseModel):
    """
    Represent the response generated by the chat API.

    Includes the classification metadata, selected handler, generated answer,
    and optional performance information for the complete request.
    """

    model_config = ConfigDict(extra="forbid")

    request_id: str = Field(
        ...,
        min_length=1,
        description="Unique identifier for the request.",
    )
    category: str = Field(
        ...,
        description="Resolved category of the query.",
    )
    urgency: str = Field(
        ...,
        description="Assessed urgency level.",
    )
    target_agent: str = Field(
        ...,
        min_length=1,
        description="Handler selected to process the query.",
    )
    answer: str = Field(
        ...,
        description="Generated response from the selected handler.",
    )
    status: str = Field(
        default="success",
        description="Request status, such as success or error.",
    )
    complexity: Optional[str] = Field(
        default=None,
        description="Assessed query complexity.",
    )
    confidence: Optional[float] = Field(
        default=None,
        ge=0.0,
        le=1.0,
        description="Classification confidence score, when available.",
    )
    requires_clarification: bool = Field(
        default=False,
        description="Whether the query requires additional clarification.",
    )
    total_latency_ms: Optional[float] = Field(
        default=None,
        ge=0.0,
        description="Total processing time for the request, in milliseconds.",
    )


class HealthResponse(BaseModel):
    """
    Represent the application's health-check response.

    Exposes basic operational metadata without including credentials
    or other sensitive configuration values.
    """

    model_config = ConfigDict(extra="forbid")

    status: str = Field(
        default="ok",
        description="Health check status.",
    )
    app_name: str = Field(
        ...,
        min_length=1,
        description="Name of the application.",
    )
    version: str = Field(
        ...,
        min_length=1,
        description="Application version.",
    )
    environment: str = Field(
        ...,
        min_length=1,
        description="Current deployment environment.",
    )
    model: str = Field(
        ...,
        min_length=1,
        description="Configured Gemini model identifier; no secrets exposed.",
    )


class ErrorResponse(BaseModel):
    """
    Represent a standardized API error response.

    Provides a request identifier, status indicator, safe error description,
    and machine-readable error type for troubleshooting and monitoring.
    """

    model_config = ConfigDict(extra="forbid")

    request_id: str = Field(
        ...,
        min_length=1,
        description="Unique identifier associated with the failed request.",
    )
    status: str = Field(
        default="error",
        description="Error status indicator.",
    )
    error: str = Field(
        ...,
        min_length=1,
        description="Safe, human-readable error description.",
    )
    error_type: str = Field(
        ...,
        min_length=1,
        description="Machine-readable error type identifier.",
    )